import prisma from '../../db/prisma';
import { AppError } from '../../shared/errors/AppError';
import { ticketsService } from '../tickets/tickets.service';
import fs from 'fs';
import path from 'path';

export class AttachmentsService {
  async uploadAttachment(organizationId: string, ticketId: string, actorId: string, file: Express.Multer.File, user: any) {
    // Check ticket access
    const ticket = await ticketsService.getTicket(ticketId, organizationId, user);

    const attachment = await prisma.attachment.create({
      data: {
        organizationId,
        ticketId,
        fileName: file.originalname,
        fileUrl: file.filename, // we store the filename generated by multer
        mimeType: file.mimetype,
        sizeBytes: file.size,
        uploadedById: actorId
      }
    });

    await prisma.ticketActivity.create({
      data: {
        organizationId,
        ticketId,
        actorId,
        action: 'ATTACHMENT_ADDED',
        newValue: file.originalname
      }
    });

    return attachment;
  }

  async listAttachments(organizationId: string, ticketId: string, user: any) {
    await ticketsService.getTicket(ticketId, organizationId, user);
    
    return prisma.attachment.findMany({
      where: { ticketId, organizationId },
      orderBy: { createdAt: 'desc' }
    });
  }

  async downloadAttachment(organizationId: string, attachmentId: string, user: any) {
    const attachment = await prisma.attachment.findFirst({
      where: { id: attachmentId, organizationId }
    });

    if (!attachment) {
      throw new AppError('Attachment not found', 404);
    }

    // Verify ticket access
    await ticketsService.getTicket(attachment.ticketId, organizationId, user);

    const filePath = path.join(process.cwd(), 'uploads', attachment.fileUrl);
    if (!fs.existsSync(filePath)) {
      throw new AppError('File not found on server', 404);
    }

    return { filePath, fileName: attachment.fileName, mimeType: attachment.mimeType };
  }

  async deleteAttachment(organizationId: string, attachmentId: string, actorId: string, user: any) {
    const attachment = await prisma.attachment.findFirst({
      where: { id: attachmentId, organizationId }
    });

    if (!attachment) {
      throw new AppError('Attachment not found', 404);
    }

    await ticketsService.getTicket(attachment.ticketId, organizationId, user);

    await prisma.attachment.delete({
      where: { id: attachmentId }
    });

    const filePath = path.join(process.cwd(), 'uploads', attachment.fileUrl);
    if (fs.existsSync(filePath)) {
      fs.unlinkSync(filePath);
    }

    await prisma.ticketActivity.create({
      data: {
        organizationId,
        ticketId: attachment.ticketId,
        actorId,
        action: 'ATTACHMENT_REMOVED',
        oldValue: attachment.fileName
      }
    });

    return { success: true };
  }
}

export const attachmentsService = new AttachmentsService();
